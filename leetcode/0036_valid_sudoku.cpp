#include <gmock/gmock.h>

#include <vector>

namespace p0036 {
bool isValidSudoku(const std::vector<std::vector<char>>& board) {
  std::array<int, 9> rows{}, cols{}, boxes{};
  for (int r = 0; r < 9; ++r) {
    for (int c = 0; c < 9; ++c) {
      const char ch = board[r][c];
      if (ch == '.') continue;
      const int b = (r / 3) * 3 + (c / 3);
      const int bit = 1 << (ch - '1');
      if ((rows[r] | cols[c] | boxes[b]) & bit) return false;
      rows[r] |= bit;
      cols[c] |= bit;
      boxes[b] |= bit;
    }
  }
  return true;
}
}  // namespace p0036

TEST(P0036, Basic) {
  EXPECT_TRUE(p0036::isValidSudoku({{'5', '3', '.', '.', '7', '.', '.', '.', '.'},
                                    {'6', '.', '.', '1', '9', '5', '.', '.', '.'},
                                    {'.', '9', '8', '.', '.', '.', '.', '6', '.'},
                                    {'8', '.', '.', '.', '6', '.', '.', '.', '3'},
                                    {'4', '.', '.', '8', '.', '3', '.', '.', '1'},
                                    {'7', '.', '.', '.', '2', '.', '.', '.', '6'},
                                    {'.', '6', '.', '.', '.', '.', '2', '8', '.'},
                                    {'.', '.', '.', '4', '1', '9', '.', '.', '5'},
                                    {'.', '.', '.', '.', '8', '.', '.', '7', '9'}}));

  EXPECT_FALSE(p0036::isValidSudoku({{'8', '3', '.', '.', '7', '.', '.', '.', '.'},
                                     {'6', '.', '.', '1', '9', '5', '.', '.', '.'},
                                     {'.', '9', '8', '.', '.', '.', '.', '6', '.'},
                                     {'8', '.', '.', '.', '6', '.', '.', '.', '3'},
                                     {'4', '.', '.', '8', '.', '3', '.', '.', '1'},
                                     {'7', '.', '.', '.', '2', '.', '.', '.', '6'},
                                     {'.', '6', '.', '.', '.', '.', '2', '8', '.'},
                                     {'.', '.', '.', '4', '1', '9', '.', '.', '5'},
                                     {'.', '.', '.', '.', '8', '.', '.', '7', '9'}}));

  EXPECT_FALSE(p0036::isValidSudoku({{'.', '.', '.', '.', '5', '.', '.', '1', '.'},
                                     {'.', '4', '.', '3', '.', '.', '.', '.', '.'},
                                     {'.', '.', '.', '.', '.', '3', '.', '.', '1'},
                                     {'8', '.', '.', '.', '.', '.', '.', '2', '.'},
                                     {'.', '.', '2', '.', '7', '.', '.', '.', '.'},
                                     {'.', '1', '5', '.', '.', '.', '.', '.', '.'},
                                     {'.', '.', '.', '.', '.', '2', '.', '.', '.'},
                                     {'.', '2', '.', '9', '.', '.', '.', '.', '.'},
                                     {'.', '.', '4', '.', '.', '.', '.', '.', '.'}}));
};
